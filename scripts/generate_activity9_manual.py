def P(text: str, style: str = "body") -> Paragraph:
    return Paragraph(text, S[style])


def bullets(items: list[str]) -> list:
    return [P("• " + item, "bullet") for item in items]


def note(title: str, text: str, color=BLUE) -> Table:
    t = Table([[P(f"<b>{title}</b><br/>{text}", "note")]], colWidths=[168 * mm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), LIGHT),
        ("BOX", (0, 0), (-1, -1), 0.7, color),
        ("LINEBEFORE", (0, 0), (0, -1), 4, color),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
    ]))
    return t


def table(headers: list[str], rows: list[list[str]], widths: list[float] | None = None) -> LongTable:
    data = [[P(x, "table_h") for x in headers]] + [[P(str(x), "table") for x in row] for row in rows]
    t = LongTable(data, colWidths=[w * mm for w in widths] if widths else None, repeatRows=1, hAlign="LEFT")
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), NAVY),
        ("GRID", (0, 0), (-1, -1), 0.45, LINE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
    ]))
    return t


def screenshot(filename: str, caption: str, max_h_mm: float = 173) -> list:
    path = SCREENS / filename
    if not path.exists():
        return [note("ไม่พบภาพหน้าจอ", str(path), RED)]
    reader = ImageReader(str(path))
    w, h = reader.getSize()
    max_w = 168 * mm
    max_h = max_h_mm * mm
    scale = min(max_w / w, max_h / h)
    img = Image(str(path), width=w * scale, height=h * scale)
    img.hAlign = "CENTER"
    return [img, P(caption, "caption")]


