class ManualDocTemplate(BaseDocTemplate):
    def __init__(self, filename: str, **kwargs):
        super().__init__(filename, **kwargs)
        frame = Frame(
            self.leftMargin,
            self.bottomMargin,
            self.width,
            self.height,
            id="normal",
            leftPadding=0,
            rightPadding=0,
            topPadding=0,
            bottomPadding=0,
        )
        self.addPageTemplates(PageTemplate(id="manual", frames=frame, onPage=self._page))

    def _page(self, canvas, doc):
        canvas.saveState()
        if doc.page > 1:
            canvas.setStrokeColor(colors.HexColor("#D9E2EC"))
            canvas.setLineWidth(0.45)
            canvas.line(doc.leftMargin, 16 * mm, A4[0] - doc.rightMargin, 16 * mm)
            canvas.setFont("THSarabun", 10)
            canvas.setFillColor(colors.HexColor("#66788A"))
            canvas.drawString(doc.leftMargin, 10.8 * mm, "E-CMIS กิจกรรมที่ 9 — ระบบฐานข้อมูลการดำเนินการตามหมายจับ")
            canvas.drawRightString(A4[0] - doc.rightMargin, 10.8 * mm, f"หน้า {doc.page}")
        canvas.restoreState()


